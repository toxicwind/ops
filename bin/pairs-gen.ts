#!/usr/bin/env bun
/**
 * pairs-gen — generate a rename .pairs file from old=>new + auto-armored excludes.
 * Derived case/compound/path/env variants + auto-excludes of live compound identifiers.
 */
import { readdirSync } from "node:fs"

const argv = process.argv.slice(2)
const values: Record<string, any> = {}
for (let i = 0; i < argv.length; i++) {
  const a = argv[i]!
  if (!a.startsWith("--")) continue
  const key = a.slice(2)
  const next = argv[i + 1]
  if (next === undefined || next.startsWith("--")) { values[key] = true; continue }
  if (key === "extra-exclude") { (values[key] ??= []).push(next); i++; continue }
  values[key] = next; i++
}
const old: string = values.old ?? ""
const neu: string = values.new
const repo: string = values.repo
const out: string = values.out
const noArmor: boolean = !!values["no-armor"]
const extraExcludes: string[] = values["extra-exclude"] ?? []
const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1)
const up = (s: string) => s.toUpperCase()

const wordRules: Array<[string, string]> = [[old, neu], [cap(old), cap(neu)], [up(old), up(neu)]]
const substrRules: Array<[string, string]> = []
for (const sep of ["-", "_", ".", "/"]) {
  substrRules.push([`${old}${sep}`, `${neu}${sep}`], [`${sep}${old}`, `${sep}${neu}`])
}
substrRules.push([`${up(old)}_`, `${up(neu)}_`], [`${up(old)}-`, `${up(neu)}-`])

const excludes = new Set<string>(extraExcludes)
if (!noArmor) {
  const p = Bun.spawnSync(["grep", "-rhoE", `[A-Za-z_-]*${up(old)}[A-Za-z_-]*`, repo, "--exclude-dir=node_modules", "--exclude-dir=.git"], { stdout: "pipe", stderr: "pipe" })
  const freq = new Map<string, number>()
  for (const h of p.stdout.toString().split("\n")) {
    if (!h) continue
    freq.set(h, (freq.get(h) ?? 0) + 1)
  }
  for (const [ident, n] of [...freq.entries()].sort((a, b) => b[1] - a[1])) {
    if (ident === up(old)) continue
    if (n >= 2) excludes.add(ident) // compound live identifiers get armored
  }
}

const L: string[] = [
  `# ${neu} rename pairs — ${old} -> ${neu} (generated by pairs-gen; review before apply)`,
  "#",
  "# Word: OLD => NEW (whole word) | substr: substring | exclude: armored identifier",
  "",
  "# ---- auto-armor (live compound identifiers; unexclude deliberately) ----",
  ...[...excludes].sort().map((e) => `exclude: ${e}`),
  "",
  "# ---- code identifiers ----",
  ...wordRules.map(([a, b]) => `word: ${a} => ${b}`),
  "",
  "# ---- compound / path forms ----",
  ...substrRules.map(([a, b]) => `substr: ${a} => ${b}`),
]
await Bun.write(out, L.join("\n") + "\n")
console.log(`wrote ${out} (${wordRules.length} word + ${substrRules.length} substr rules, ${excludes.size} armored excludes)`)
