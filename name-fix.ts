#!/usr/bin/env bun
/**
 * name-fix — Estate name fixer: check availability, generate pairs, rename.
 * Composes name-check + lib/pairs + lib/rename so a rebrand is one command.
 */
import { $ } from "bun";
import { resolve } from "node:path";
import { writeFileSync, existsSync, readFileSync } from "node:fs";
import { checkName } from "./bin/name-check.ts";
import { runRename } from "/home/toxic/pens/ranch/products/rename-roundup/lib/index.ts";
import { parsePairsFile, findConflict } from "/home/toxic/pens/ranch/products/rename-roundup/lib/rules.ts";
import { tokenVariants } from "/home/toxic/pens/ranch/products/rename-roundup/lib/rules.ts";

const ESTATE = "/home/toxic/pens/estate";

function compoundPairs(oldName: string, newName: string): string[] {
	const o = tokenVariants(oldName);
	const n = tokenVariants(newName);
	const seps = ["_", "-", "/", "."];
	const rules: string[] = [];
	for (const sep of seps) {
		rules.push(`substr: ${o.lower}${sep} => ${n.lower}${sep}`);
		rules.push(`substr: ${o.UPPER}${sep} => ${n.UPPER}${sep}`);
		rules.push(`substr: ${o.Upper}${sep} => ${n.Upper}${sep}`);
		rules.push(`substr: ${sep}${o.lower} => ${sep}${n.lower}`);
		rules.push(`substr: ${sep}${o.UPPER} => ${sep}${n.UPPER}`);
	}
	return rules;
}

export function generatePairs(oldName: string, newName: string): string {
	const o = tokenVariants(oldName);
	const n = tokenVariants(newName);
	return [
		`# Auto-generated by name-fix — ${oldName} -> ${newName}`,
		`# Generated: ${new Date().toISOString()}`,
		"",
		"# Bare tokens (word boundary, case variants)",
		`word: ${o.lower} => ${n.lower}`,
		`word: ${o.Upper} => ${n.Upper}`,
		`word: ${o.UPPER} => ${n.UPPER}`,
		"",
		"# Separator compounds (substr — \\b does not split on _ - / .)",
		...compoundPairs(oldName, newName),
		"",
		"# Daemon id forms",
		`substr: daemons.${o.lower} => daemons.${n.lower}`,
		`substr: estate/${o.lower} => estate/${n.lower}`,
	].join("\n") + "\n";
}

async function main(): Promise<void> {
	const args = process.argv.slice(2);
	const oldName = args[0];
	const newName = args[1];
	const repoIdx = args.indexOf("--repo");
	const repo = repoIdx >= 0 ? resolve(args[repoIdx + 1]) : ESTATE;
	const execute = args.includes("--execute");
	const dryRunOnly = args.includes("--dry-run-only");
	const force = args.includes("--force");

	if (!oldName || !newName) {
		console.error("Usage: bun run name-fix.ts <old> <new> [--repo <git-root>] [--execute] [--dry-run-only]");
		process.exit(1);
	}
	if (oldName === newName) { console.error("old and new names are identical"); process.exit(1); }

	console.log(`── 1/3 availability check: '${newName}'`);
	const check = await checkName(newName);
	const repoPrefix = repo.replace(/\/$/, "") + "/";
	const external = check.conflicts.filter((c) => !c.match.startsWith(repoPrefix));
	if (external.length > 0 && !force) {
		console.error(`❌ '${newName}' is taken outside the target repo (pass --force to override):`);
		for (const c of external.slice(0, 15)) console.error(`   ${c.source}: ${c.match}`);
		process.exit(1);
	}
	if (external.length > 0) console.log(`⚠️ --force: ${external.length} external conflict(s) overridden`);
	console.log(`✅ free (conflicts limited to target repo: ${check.conflicts.length})`);

	const pairsPath = `${ESTATE}/docs/name-fix-${oldName}-to-${newName}.pairs`;
	writeFileSync(pairsPath, generatePairs(oldName, newName));
	console.log(`── 2/3 pairs generated + written: ${pairsPath}`);

	const { rules, excludes } = parsePairsFile(pairsPath, readFileSync(pairsPath, "utf8"));
	const c = findConflict(rules);
	if (c) { console.error(`❌ conflicting pairs rule: ${c.old} routed to two targets`); process.exit(1); }
	// generatePairs doesn't emit excludes; keep armor empty and rely on doc/archive protection.
	const safeNew = newName;
	console.log(`── 3/3 rename dry-run on ${repo}`);
	const res = await runRename({
		repo,
		rules,
		excludes,
		extraProtected: [pairsPath.replace(/^\/home\/toxic\//, "")],
		dryRun: true,
	});
	console.log(`dry-run: ${res.changedContent.length} content + ${res.renames.length} renames, ${res.protectedSkipped} protected skipped`);
	for (const f of res.changedContent.slice(0, 30)) console.log(`  M ${f}`);

	if (dryRunOnly) { console.log("dry-run-only: stopping before execute."); return; }
	if (!execute) { console.log("Dry run complete. Re-run with --execute to apply + commit."); return; }

	await runRename({
		repo,
		rules,
		excludes,
		extraProtected: [pairsPath.replace(/^\/home\/toxic\//, "")],
		commitMsg: `rename: ${oldName} -> ${safeNew} (name-fix: check → pairs → rename)`,
	});
	console.log(`✅ renamed '${oldName}' -> '${safeNew}' and committed. rollback: git -C ${repo} reset --hard HEAD~1`);
}

main();